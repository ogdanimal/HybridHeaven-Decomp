#!/usr/bin/env python3
"""
Which fingerprinted libultra names would do real damage if they were wrong?

`tools/fingerprint_libultra.py` recovers libultra names by matching masked
object code against the mnsg decomp. It is careful, but it is still a heuristic,
and its output is not merely documentation: N64Recomp matches libultra purely by
FUNCTION NAME (`src/main.cpp`, the reimplemented_funcs/ignored_funcs/renamed_funcs
dispatch), and a name in one of those sets changes what the built port runs.

  reimplemented_funcs  the game's own code is NOT recompiled; every call goes to
                       the runtime's native implementation instead. A false
                       positive here silently swaps a game function for an
                       unrelated libultra one.
  ignored_funcs        the function is not recompiled either, and nothing is
                       generated to replace it.
  renamed_funcs        recompiled as normal, just under another name -- the
                       benign case.

So the names that matter are the intersection of what we guessed with what the
recompiler acts on. Everything outside that intersection is a label; everything
inside it is a behavioural decision.

The at-risk set is committed as a baseline next to this script, and the tool
fails when the live set differs from it. Demanding hand-written evidence for all
89 would be permanently red and therefore ignored; what is actually worth an
alarm is the set CHANGING -- an upstream N64Recomp bump that adds a name to
reimplemented_funcs which we happen to have fingerprinted is precisely the
silent substitution this guards against, and it arrives without touching this
repo at all.

    uv run python tools/fingerprint_risk.py
    uv run python tools/fingerprint_risk.py --update   # accept the current set
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).parent.parent
DEFAULT_RECOMP = (
    # Local directory name, deliberately NOT renamed with the repo: the GitHub
    # repo is HybridHeaven-Recomp, the working directory beside this one is not.
    REPO.parent / "HybridHeavenRecomp/lib/N64ModernRuntime/N64Recomp"
)

SYM_RE = re.compile(r"^(\w+)\s*=\s*0x", re.M)


def read_syms(path: Path) -> set[str]:
    return set(SYM_RE.findall(path.read_text())) if path.exists() else set()


def read_list(src: str, name: str) -> set[str]:
    """Pull one brace-delimited unordered_set<string> initialiser out of symbol_lists.cpp."""
    m = re.search(
        r"unordered_set<std::string>\s+N64Recomp::" + name + r"\s*\{(.*?)\n\};",
        src,
        re.S,
    )
    if not m:
        return set()
    return set(re.findall(r'"([^"]+)"', m.group(1)))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--recomp", type=Path, default=DEFAULT_RECOMP)
    ap.add_argument("--version", default="usa")
    ap.add_argument("--update", action="store_true",
                    help="rewrite the committed baseline to match the current set")
    args = ap.parse_args()

    syms = REPO / "config" / args.version / "symbol_addrs"
    fingerprinted = read_syms(syms / "libultra_syms.txt")
    hand = read_syms(syms / "symbol_addrs.txt")

    lists_path = args.recomp / "src" / "symbol_lists.cpp"
    if not lists_path.exists():
        print(f"symbol_lists.cpp not found under {args.recomp}", file=sys.stderr)
        return 2
    src = lists_path.read_text()
    reimplemented = read_list(src, "reimplemented_funcs")
    ignored = read_list(src, "ignored_funcs")
    renamed = read_list(src, "renamed_funcs")

    print(f"fingerprinted names:      {len(fingerprinted)}")
    print(f"hand-asserted names:      {len(hand)}")
    print(f"reimplemented_funcs:      {len(reimplemented)}")
    print(f"ignored_funcs:            {len(ignored)}")
    print(f"renamed_funcs:            {len(renamed)}")

    acted_on = reimplemented | ignored
    at_risk = sorted(fingerprinted & acted_on)
    benign = sorted(fingerprinted & renamed)

    print()
    print(f"fingerprinted AND acted on by the recompiler: {len(at_risk)}")
    print(f"fingerprinted AND only renamed (harmless):    {len(benign)}")

    baseline_path = REPO / "tools" / "fingerprint_risk_baseline.txt"

    def render() -> str:
        out = [
            "# Fingerprinted libultra names that N64Recomp acts on, so a wrong",
            "# guess changes what the port runs. Generated by",
            "# tools/fingerprint_risk.py; regenerate with --update and say why in",
            "# the commit message.",
            "#",
            "# reimplemented = the game's code is replaced by a native implementation.",
            "# ignored       = the game's code is not recompiled.",
            "",
        ]
        for n in at_risk:
            out.append(f"{'reimplemented' if n in reimplemented else 'ignored':<14} {n}")
        return "\n".join(out) + "\n"

    if args.update:
        baseline_path.write_text(render())
        print(f"\nwrote {baseline_path.relative_to(REPO)} ({len(at_risk)} names)")
        return 0

    if not baseline_path.exists():
        print(f"\nno baseline at {baseline_path.relative_to(REPO)} -- create it with --update")
        return 1

    prev = {
        line.split()[1]
        for line in baseline_path.read_text().splitlines()
        if line.strip() and not line.startswith("#")
    }
    added = sorted(set(at_risk) - prev)
    removed = sorted(prev - set(at_risk))

    if added or removed:
        print("\nthe at-risk set has CHANGED since the baseline:")
        for n in added:
            which = "reimplemented" if n in reimplemented else "ignored"
            print(f"  + {n:<28} now {which}")
        for n in removed:
            print(f"  - {n:<28} no longer acted on")
        print("\nA name entering this set means the recompiler now substitutes or skips")
        print("something we only ever identified by fingerprint. Confirm each one is")
        print("really that libultra function, then rerun with --update.")
        return 1

    print(f"\nat-risk set unchanged from the baseline ({len(at_risk)} names).")
    hand_backed = sum(1 for n in at_risk if n in hand)
    print(f"{hand_backed} of them are also asserted by hand in symbol_addrs.txt.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
