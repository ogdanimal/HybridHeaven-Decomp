#!/usr/bin/env python3
"""
Generates config/<version>/overlay_syms.ld -- absolute addresses for references
that cross from one overlay into another.

Overlays that share a RAM slot share a vram range: 41 different archive files
load at 0x8038CFC0. So when one overlay does

    lui   $v1, %hi(0x8038D8D0)
    addiu $v1, $v1, %lo(0x8038D8D0)

it is naming an *address in a slot*, not a symbol in a particular file. Which
overlay is sitting there is a runtime question the link cannot answer.

splat still has to attribute the address to some segment, and picks whichever
file's ROM range maps there -- arbitrarily, among the tenants. It emits a label
at that spot, but as a `.L` local, which GNU as drops from the symbol table, so
the reference fails to resolve:

    undefined reference to `.L8038D8D0_833120'

Defining these as absolute linker symbols says what is actually true: the target
is a fixed address. No bytes change either way -- the linker resolves the
%hi/%lo pair to the same value.

The list is recovered by attempting the link and reading back what it could not
resolve, so this needs an otherwise-complete build to regenerate:

    uv run python tools/gen_overlay_syms.py   # repeat until it reports 0 new

Each run *adds* to the file rather than replacing it. Resolving one batch of
symbols lets the link get further and surface the next, so the list converges
over a few runs. Delete the file first if you want to rebuild it from scratch.

The output is committed, so a clean checkout builds without running it.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent

# splat's generated names encode the address: `.L<vram>_<rom>`, `D_<vram>`,
# `func_<vram>`. The vram is what we need; the rom suffix only disambiguates.
PATTERNS = [
    re.compile(r"^\.L([0-9A-F]{8})_[0-9A-F]+$"),
    re.compile(r"^D_([0-9A-F]{8})$"),
    re.compile(r"^func_([0-9A-F]{8})$"),
]


def undefined_symbols(version: str) -> list[str]:
    """Runs the link and returns every symbol it could not resolve."""
    proc = subprocess.run(
        ["make", f"VERSION={version}", "-j"],
        cwd=ROOT, capture_output=True, text=True,
    )
    found = re.findall(r"undefined reference to `([^']+)'", proc.stderr + proc.stdout)
    return sorted(set(found))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="usa")
    args = ap.parse_args()

    dest = ROOT / "config" / args.version / "overlay_syms.ld"

    # Carry over what is already known: each run only surfaces the symbols that
    # blocked *this* link, and resolving them reveals the next batch.
    known: dict[str, int] = {}
    if dest.exists():
        for line in dest.read_text().splitlines():
            m = re.match(r"^(\S+) = 0x([0-9A-F]+);", line)
            if m:
                known[m.group(1)] = int(m.group(2), 16)

    syms = [s for s in undefined_symbols(args.version) if s not in known]
    if not syms:
        print(f"0 new symbols; {len(known)} already in {dest.relative_to(ROOT)}")
        return 0

    entries, unknown = [], []
    for s in syms:
        for pat in PATTERNS:
            m = pat.match(s)
            if m:
                entries.append((s, int(m.group(1), 16)))
                break
        else:
            unknown.append(s)

    if unknown:
        print("Symbols whose address is not encoded in the name -- these are real\n"
              "unresolved references, not slot addresses, and need looking at:",
              file=sys.stderr)
        for s in unknown:
            print(f"  {s}", file=sys.stderr)
        return 1

    out = [
        "/* Absolute addresses for cross-overlay references.",
        " * GENERATED by tools/gen_overlay_syms.py -- do not hand-edit.",
        " *",
        " * Overlays sharing a RAM slot share a vram range, so an address like",
        " * 0x8038CFC0 belongs to whichever overlay is loaded there at runtime, not",
        " * to any one file. Defining these absolutely is what lets the link",
        " * resolve them; it changes no bytes.",
        " */",
    ]
    known.update(entries)
    for name, vram in sorted(known.items(), key=lambda e: (e[1], e[0])):
        out.append(f"{name} = 0x{vram:08X};")

    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest.relative_to(ROOT)}: {len(entries)} new, {len(known)} total")
    return 0


if __name__ == "__main__":
    sys.exit(main())
